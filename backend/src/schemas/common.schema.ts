// backend/src/schemas/common.schema.ts
import { z } from 'zod';

// ============================================================
// ТЕЛЕФОН
// ============================================================
export const phoneSchema = z.string()
  .min(10, 'Минимум 10 цифр')
  .max(12, 'Максимум 12 цифр')
  .transform((val) => val.replace(/\D/g, ''))
  .refine(
    (val) => {
      if (val.length === 10) return true;
      if (val.length === 11 && (val.startsWith('7') || val.startsWith('8'))) return true;
      return false;
    },
    { message: 'Неверный формат номера' }
  );

// ============================================================
// EMAIL
// ============================================================
export const emailSchema = z.string()
  .email('Неверный формат email')
  .min(3, 'Email слишком короткий')
  .max(255, 'Email слишком длинный');

// ============================================================
// ИМЯ И ФАМИЛИЯ
// ============================================================
export const nameSchema = z.string()
  .min(2, 'Минимум 2 символа')
  .max(50, 'Максимум 50 символов')
  .regex(/^[a-zA-Zа-яА-ЯёЁ\s-]+$/, 'Только буквы, пробелы и дефисы');

export const optionalNameSchema = nameSchema.optional().or(z.literal(''));

// ============================================================
// ПАРОЛЬ
// ============================================================
export const passwordSchema = z.string()
  .min(8, 'Минимум 8 символов')
  .regex(/[A-Z]/, 'Должна быть заглавная буква')
  .regex(/[a-z]/, 'Должна быть строчная буква')
  .regex(/[0-9]/, 'Должна быть цифра');

// ============================================================
// АДРЕС
// ============================================================
export const addressSchema = z.string()
  .min(5, 'Минимум 5 символов')
  .max(500, 'Максимум 500 символов');

// ============================================================
// ID (UUID или cuid)
// ============================================================
export const idSchema = z.string().min(1, 'ID обязателен');

// ============================================================
// КОД ПОДТВЕРЖДЕНИЯ
// ============================================================
export const codeSchema = z.string()
  .length(6, 'Код должен быть 6 цифр')
  .regex(/^\d{6}$/, 'Только цифры');